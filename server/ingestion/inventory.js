// Renders the "discovered files" table for docs/RESOURCE_INVENTORY.md from a real ingestion report.
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

export function renderInventory(report) {
  const lines = [];
  lines.push(`_Generated by \`npm run ingest\` on ${report.finishedAt}. ${report.totals.files} file(s) discovered under \`resources/\`._`, '');
  lines.push('| File | Format | Size | Status | Detected as | Records | Source / license |', '| --- | --- | ---: | --- | --- | --- | --- |');
  for (const f of report.files) {
    const c = f.counts ? Object.entries(f.counts).filter(([, n]) => n).map(([k, n]) => `${n} ${k}`).join(', ') : '';
    lines.push(`| \`${esc(f.path)}\` | ${esc(f.format)} | ${f.size} | ${f.status}${f.prevStatus ? ` (${f.prevStatus})` : ''} | ${esc(f.detected || '')} | ${esc(c)} | ${esc(f.provenance.source)} — ${esc(f.provenance.license)} |`);
  }
  const notable = report.files.filter((f) => f.notes?.length);
  if (notable.length) {
    lines.push('', '### Parser notes and flagged records', '');
    for (const f of notable) {
      lines.push(`- \`${esc(f.path)}\` (${f.status}):`);
      for (const n of f.notes.slice(0, 6)) lines.push(`  - ${esc(n)}`);
      if (f.notes.length > 6) lines.push(`  - … ${f.notes.length - 6} more`);
    }
  }
  const bad = report.files.filter((f) => f.status === 'unparsed');
  lines.push('', '### Files that could not be parsed', '');
  lines.push(bad.length ? bad.map((f) => `- \`${esc(f.path)}\`: ${esc((f.notes || []).join(' '))}`).join('\n') : '_None in the current run._');
  return lines.join('\n');
}
